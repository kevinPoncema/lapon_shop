<?php

namespace App\Models;

use Database\Factories\OrderFactory;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\HasOne;
use Illuminate\Support\Carbon;

/**
 * @property string $id
 * @property string $tenant_id
 * @property string $order_number
 * @property string $status
 * @property array<string, mixed> $customer_info
 * @property array<string, mixed> $shipping_address
 * @property string $subtotal
 * @property string $auto_discount_total
 * @property string $coupon_discount_total
 * @property string $shipping_fee
 * @property string $total_net
 * @property string|null $applied_promotion_id
 * @property string|null $applied_coupon_id
 * @property string $whatsapp_url
 * @property Carbon|null $completed_at
 * @property Carbon|null $cancelled_at
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
class Order extends Model
{
    /** @use HasFactory<OrderFactory> */
    use HasFactory, HasUuids;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'tenant_id',
        'order_number',
        'status',
        'customer_info',
        'shipping_address',
        'subtotal',
        'auto_discount_total',
        'coupon_discount_total',
        'shipping_fee',
        'total_net',
        'applied_promotion_id',
        'applied_coupon_id',
        'whatsapp_url',
        'completed_at',
        'cancelled_at',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'customer_info' => 'array',
            'shipping_address' => 'array',
            'subtotal' => 'decimal:2',
            'auto_discount_total' => 'decimal:2',
            'coupon_discount_total' => 'decimal:2',
            'shipping_fee' => 'decimal:2',
            'total_net' => 'decimal:2',
            'completed_at' => 'datetime',
            'cancelled_at' => 'datetime',
        ];
    }

    /**
     * The tenant that owns the order.
     *
     * @return BelongsTo<Tenant, $this>
     */
    public function tenant(): BelongsTo
    {
        return $this->belongsTo(Tenant::class, 'tenant_id');
    }

    /**
     * Automatic promotion applied to the order, if any.
     *
     * @return BelongsTo<Promotion, $this>
     */
    public function appliedPromotion(): BelongsTo
    {
        return $this->belongsTo(Promotion::class, 'applied_promotion_id');
    }

    /**
     * Manual coupon applied to the order, if any.
     *
     * @return BelongsTo<Coupon, $this>
     */
    public function appliedCoupon(): BelongsTo
    {
        return $this->belongsTo(Coupon::class, 'applied_coupon_id');
    }

    /**
     * Line items in the order.
     *
     * @return HasMany<OrderItem, $this>
     */
    public function items(): HasMany
    {
        return $this->hasMany(OrderItem::class, 'order_id');
    }

    /**
     * Commission associated with the order.
     *
     * @return HasOne<Commission, $this>
     */
    public function commission(): HasOne
    {
        return $this->hasOne(Commission::class, 'order_id');
    }

    /**
     * Outbound vouchers generated by this order.
     *
     * @return HasMany<OutboundReward, $this>
     */
    public function outboundRewards(): HasMany
    {
        return $this->hasMany(OutboundReward::class, 'order_id');
    }
}
